-- ===========================================================================
--  001_core — базовая схема. Обычный PostgreSQL, без TimescaleDB.
--  Выполняется приложением при старте, идемпотентно.
--
--  Качество значения (семантика OPC UA):
--    0 GOOD        значение прочитано и декодировано успешно
--    1 BAD_COMM    нет связи с устройством / таймаут / Modbus exception
--    2 BAD_RANGE   значение вне заданных min/max
--    3 BAD_DECODE  ошибка декодирования
--    4 STALE       значение не обновлялось, записано как «сердцебиение»
-- ===========================================================================

-- --------------------------------------------------------------------------
--  Иерархия цифрового двойника: площадка → участок → линия → машина
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS twin_node (
    node_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   integer REFERENCES twin_node (node_id) ON DELETE CASCADE,
    kind        text        NOT NULL DEFAULT 'machine',   -- site|area|line|machine
    name        text        NOT NULL,
    description text,
    sort_order  integer     NOT NULL DEFAULT 0,
    meta        jsonb       NOT NULL DEFAULT '{}'::jsonb,
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT twin_node_kind_chk CHECK (kind IN ('site', 'area', 'line', 'machine'))
);

CREATE INDEX IF NOT EXISTS twin_node_parent_idx ON twin_node (parent_id);

-- --------------------------------------------------------------------------
--  Устройства (источники данных). Раньше жили в config.yaml.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS device (
    device_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  text        NOT NULL UNIQUE,
    description           text,
    node_id               integer REFERENCES twin_node (node_id) ON DELETE SET NULL,
    transport             text        NOT NULL DEFAULT 'tcp',   -- tcp|udp|rtu
    host                  text,
    port                  integer     NOT NULL DEFAULT 502,
    unit_id               integer     NOT NULL DEFAULT 1,
    serial_port           text,
    baudrate              integer     NOT NULL DEFAULT 9600,
    bytesize              integer     NOT NULL DEFAULT 8,
    parity                text        NOT NULL DEFAULT 'N',
    stopbits              integer     NOT NULL DEFAULT 1,
    timeout_s             double precision NOT NULL DEFAULT 3.0,
    retries               integer     NOT NULL DEFAULT 2,
    reconnect_delay_s     double precision NOT NULL DEFAULT 2.0,
    reconnect_delay_max_s double precision NOT NULL DEFAULT 30.0,
    inter_request_delay_ms integer    NOT NULL DEFAULT 0,
    block_max_registers   integer     NOT NULL DEFAULT 100,
    block_max_gap         integer     NOT NULL DEFAULT 8,
    enabled               boolean     NOT NULL DEFAULT true,
    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT device_transport_chk CHECK (transport IN ('tcp', 'udp', 'rtu'))
);

COMMENT ON TABLE device IS 'Опрашиваемые устройства. Управляется из веб-интерфейса.';

-- --------------------------------------------------------------------------
--  Справочник тегов
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tag (
    tag_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device       text        NOT NULL,          -- имя устройства (для Grafana)
    name         text        NOT NULL,
    description  text,
    unit         text,
    datatype     text        NOT NULL,
    register     text        NOT NULL,
    address      integer     NOT NULL,
    bit          smallint,
    scale        double precision NOT NULL DEFAULT 1,
    "offset"     double precision NOT NULL DEFAULT 0,
    min_value    double precision,
    max_value    double precision,
    labels       jsonb       NOT NULL DEFAULT '{}'::jsonb,
    enabled      boolean     NOT NULL DEFAULT true,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT tag_device_name_key UNIQUE (device, name)
);

