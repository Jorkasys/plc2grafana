CREATE INDEX IF NOT EXISTS tag_device_idx    ON tag (device);
CREATE INDEX IF NOT EXISTS tag_device_id_idx ON tag (device_id);
CREATE INDEX IF NOT EXISTS tag_node_idx      ON tag (node_id);
CREATE INDEX IF NOT EXISTS tag_labels_idx    ON tag USING gin (labels);

-- --------------------------------------------------------------------------
--  Значения
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS tag_value (
    ts          timestamptz      NOT NULL,
    tag_id      integer          NOT NULL REFERENCES tag (tag_id) ON DELETE CASCADE,
    value       double precision,
    value_text  text,
    quality     smallint         NOT NULL DEFAULT 0
);

-- Основной паттерн запроса Grafana: «один тег за интервал времени»
CREATE INDEX IF NOT EXISTS tag_value_tag_ts_idx ON tag_value (tag_id, ts DESC);
-- BRIN дёшево ускоряет отсечение по времени на большой таблице без Timescale
CREATE INDEX IF NOT EXISTS tag_value_ts_brin_idx ON tag_value USING brin (ts);

-- --------------------------------------------------------------------------
--  Представления
-- --------------------------------------------------------------------------
CREATE OR REPLACE VIEW v_tag_value AS
SELECT v.ts,
       v.value,
       v.value_text,
       v.quality,
       t.tag_id,
       t.device,
       t.name,
       t.description,
       t.unit,
       t.labels,
       t.device || '.' || t.name AS full_name
FROM tag_value v
JOIN tag t USING (tag_id);

CREATE OR REPLACE VIEW v_tag_latest AS
SELECT DISTINCT ON (t.tag_id)
       t.tag_id,
       t.device,
       t.name,
       t.description,
       t.unit,
       t.labels,
       t.node_id,
       t.role,
       t.group_name,
       v.ts,
       v.value,
       v.value_text,
       v.quality,
       now() - v.ts AS age
FROM tag t
LEFT JOIN tag_value v ON v.tag_id = t.tag_id
WHERE t.enabled
ORDER BY t.tag_id, v.ts DESC;

-- Полный путь узла двойника: «Завод / Линия 1 / Розлив»
CREATE OR REPLACE VIEW v_twin_path AS
WITH RECURSIVE walk AS (
    SELECT node_id, parent_id, kind, name, name AS path, 1 AS depth
    FROM twin_node WHERE parent_id IS NULL
    UNION ALL
    SELECT n.node_id, n.parent_id, n.kind, n.name,
           w.path || ' / ' || n.name, w.depth + 1
    FROM twin_node n JOIN walk w ON n.parent_id = w.node_id
)
SELECT node_id, parent_id, kind, name, path, depth FROM walk;
